// CreateAlbum 创建相册
func (m *Manager) CreateAlbum(name, albumType string) *Album {
	m.mu.Lock()
	defer m.mu.Unlock()
	album := &Album{
		ID:        fmt.Sprintf("album-%d", time.Now().UnixNano()),
		Name:      name,
		Type:      albumType,
		CreatedAt: time.Now(),
		UpdatedAt: time.Now(),
	}
	m.albums[album.ID] = album
	m.stats.AlbumCount++
	return album
}

// GetDashboard 获取仪表盘
func (m *Manager) GetDashboard() map[string]interface{} {
	m.mu.RLock()
	defer m.mu.RUnlock()
	return map[string]interface{}{
		"stats":  m.stats,
		"albums": len(m.albums),
		"tags":   len(m.tags),
		"dupes":  len(m.dupes),
	}
}

// Handler HTTP 处理器
type Handler struct {
	manager *Manager
}

func NewHandler(manager *Manager) *Handler {
	return &Handler{manager: manager}
}

func (h *Handler) RegisterRoutes(router *gin.RouterGroup) {
	group := router.Group("/media-organizer")
	{
		group.GET("/dashboard", h.GetDashboard)
		group.GET("/albums", h.ListAlbums)
		group.POST("/albums", h.CreateAlbum)
		group.GET("/albums/:id", h.GetAlbum)
		group.GET("/tags", h.ListTags)
		group.GET("/dupes", h.ListDuplicates)
		group.POST("/dupes/clean", h.CleanDuplicates)
		group.POST("/scan", h.TriggerScan)
	}
}

func (h *Handler) GetDashboard(c *gin.Context) {
	c.JSON(http.StatusOK, gin.H{"success": true, "data": h.manager.GetDashboard()})
}

func (h *Handler) ListAlbums(c *gin.Context) {
	h.manager.mu.RLock()
	defer h.manager.mu.RUnlock()
	albums := make([]*Album, 0, len(h.manager.albums))
	for _, a := range h.manager.albums {
		albums = append(albums, a)
	}
	c.JSON(http.StatusOK, gin.H{"success": true, "data": albums})
}

func (h *Handler) CreateAlbum(c *gin.Context) {
	var req struct {
		Name string `json:"name" binding:"required"`
		Type string `json:"type"`
	}
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"success": false, "error": err.Error()})
		return
	}
	if req.Type == "" {
		req.Type = "manual"
	}
	album := h.manager.CreateAlbum(req.Name, req.Type)
	c.JSON(http.StatusCreated, gin.H{"success": true, "data": album})
}

func (h *Handler) GetAlbum(c *gin.Context) {
	id := c.Param("id")
	h.manager.mu.RLock()
	album, ok := h.manager.albums[id]
	h.manager.mu.RUnlock()
	if !ok {
		c.JSON(http.StatusNotFound, gin.H{"success": false, "error": "相册不存在"})
		return
	}
	c.JSON(http.StatusOK, gin.H{"success": true, "data": album})
}

func (h *Handler) ListTags(c *gin.Context) {
	h.manager.mu.RLock()
	defer h.manager.mu.RUnlock()
	tags := make([]*Tag, 0, len(h.manager.tags))
	for _, t := range h.manager.tags {
		tags = append(tags, t)
	}
	c.JSON(http.StatusOK, gin.H{"success": true, "data": tags})
}

func (h *Handler) ListDuplicates(c *gin.Context) {
	c.JSON(http.StatusOK, gin.H{"success": true, "data": h.manager.dupes})
}

func (h *Handler) CleanDuplicates(c *gin.Context) {
	c.JSON(http.StatusOK, gin.H{"success": true, "message": "清理任务已启动"})
}

func (h *Handler) TriggerScan(c *gin.Context) {
	go h.manager.scanMedia()
	c.JSON(http.StatusOK, gin.H{"success": true, "message": "扫描已启动"})
}
