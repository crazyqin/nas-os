// Manager 媒体整理管理器
type Manager struct {
	mu       sync.RWMutex
	config   *Config
	albums   map[string]*Album
	tags     map[string]*Tag
	dupes    []*DuplicateGroup
	stats    *MediaStats
}

// Config 配置
type Config struct {
	Enabled         bool     `json:"enabled"`
	WatchPaths      []string `json:"watch_paths"`
	AutoOrganize    bool     `json:"auto_organize"`
	AIEnabled       bool     `json:"ai_enabled"`
	DupeDetection   bool     `json:"dupe_detection"`
	ThumbSizes      []int    `json:"thumb_sizes"`
	ExcludePatterns []string `json:"exclude_patterns"`
}

// Album 相册
type Album struct {
	ID          string    `json:"id"`
	Name        string    `json:"name"`
	Description string    `json:"description"`
	Type        string    `json:"type"` // manual, ai_scene, ai_face, ai_time, smart
	CoverPath   string    `json:"cover_path"`
	MediaCount  int       `json:"media_count"`
	CreatedAt   time.Time `json:"created_at"`
	UpdatedAt   time.Time `json:"updated_at"`
	Tags        []string  `json:"tags"`
	SmartRule   *SmartRule `json:"smart_rule,omitempty"`
}

// SmartRule 智能规则
type SmartRule struct {
	Type      string   `json:"type"` // scene, face, location, time, tag
	Values    []string `json:"values"`
	MatchMode string   `json:"match_mode"` // any, all
}

// Tag 标签
type Tag struct {
	ID         string `json:"id"`
	Name       string `json:"name"`
	Count      int    `json:"count"`
	Category   string `json:"category"` // scene, object, place, custom
	AutoGenerated bool `json:"auto_generated"`
}

// DuplicateGroup 重复组
type DuplicateGroup struct {
	ID        string   `json:"id"`
	Files     []string `json:"files"`
	TotalSize int64    `json:"total_size"`
	SaveSize  int64    `json:"saveable_size"`
	Algorithm string   `json:"algorithm"` // perceptual, hash
	Score     float64  `json:"score"`     // 0-100 相似度
}

// MediaStats 媒体统计
type MediaStats struct {
	TotalFiles     int       `json:"total_files"`
	TotalSize      int64     `json:"total_size"`
	PhotoCount     int       `json:"photo_count"`
	VideoCount     int       `json:"video_count"`
	AlbumCount     int       `json:"album_count"`
	TagCount       int       `json:"tag_count"`
	DupGroupCount  int       `json:"dup_group_count"`
	DupSaveSize    int64     `json:"dup_saveable_size"`
	LastScanTime   time.Time `json:"last_scan_time"`
}

// MediaItem 媒体项
type MediaItem struct {
	ID        string    `json:"id"`
	Path      string    `json:"path"`
	Name      string    `json:"name"`
	MimeType  string    `json:"mime_type"`
	Size      int64     `json:"size"`
	Width     int       `json:"width,omitempty"`
	Height    int       `json:"height,omitempty"`
	Duration  float64   `json:"duration,omitempty"` // video duration in seconds
	TakenAt   time.Time `json:"taken_at"`
	Tags      []string  `json:"tags"`
	Albums    []string  `json:"albums"`
	Hash      string    `json:"hash"`
	Thumbnail string    `json:"thumbnail"`
}

