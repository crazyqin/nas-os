// processMessages processes incoming messages
func (s *ChatService) processMessages() {
	for {
		select {
		case <-s.ctx.Done():
			return
		case msg := <-s.messageChan:
			s.mu.Lock()
			s.messages[msg.ChannelID] = append(s.messages[msg.ChannelID], msg)
			s.mu.Unlock()
			
			log.Printf("[LocalChat] Message processed: %s in channel %s", msg.ID, msg.ChannelID)
		}
	}
}

