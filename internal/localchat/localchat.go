// generateID generates a random ID
func generateID() string {
	bytes := make([]byte, 16)
	rand.Read(bytes)
	return hex.EncodeToString(bytes)
}

// GetServiceStatus returns the current service status
func (s *ChatService) GetServiceStatus() map[string]interface{} {
	s.mu.RLock()
	defer s.mu.RUnlock()
	
	return map[string]interface{}{
		"users":     len(s.users),
		"channels":  len(s.channels),
		"messages":  s.countMessages(),
		"meetings":  len(s.meetings),
		"ai_enabled": s.ai != nil && s.ai.Enabled,
	}
}

// countMessages counts total messages across all channels
func (s *ChatService) countMessages() int {
	count := 0
	for _, msgs := range s.messages {
		count += len(msgs)
	}
	return count
}
